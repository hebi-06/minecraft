def art(rows, pal=None, one=None):
    """글자 그림 → 그림. one = 모든 칸을 이 색으로 (한 색 선 그림)"""
    pal = pal or PAL
    h = len(rows)
    w = max(len(r) for r in rows)
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch == ".":
                continue
            col = one if one else pal.get(ch)
            if col:
                img.putpixel((x, y), tuple(col[:3]) + (255,))
    return img


