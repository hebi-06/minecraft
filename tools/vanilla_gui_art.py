def crit_icon():
    """치명타 확률: 과녁 (원 띠 + 가운데)"""
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    cx = cy = 7.5
    for y in range(16):
        for x in range(16):
            d = math.hypot(x + 0.5 - 8, y + 0.5 - 8)
            col = None
            if d <= 7.6:
                col = PAL["K"]
            if d <= 6.6:
                col = PAL["R"]
            if d <= 5.2:
                col = PAL["W"]
            if d <= 3.8:
                col = PAL["R"]
            if d <= 2.2:
                col = PAL["W"]
            if d <= 1.1:
                col = PAL["r"]
            if col and d <= 6.6 and (abs(x + 0.5 - 8) < 0.6 or abs(y + 0.5 - 8) < 0.6) and d > 2.2:
                col = PAL["K"]
            if col:
                img.putpixel((x, y), col + (255,))
    return img


def burst_icon():
    """치명타 피해: 터짐 (별 모양 — 주황 · 노랑)"""
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y in range(16):
        for x in range(16):
            dx, dy = x + 0.5 - 8, y + 0.5 - 8
            d = math.hypot(dx, dy)
            a = math.atan2(dy, dx)
            r = 4.2 + 3.4 * abs(math.cos(4 * a)) ** 2
            if d <= r + 0.8:
                col = PAL["K"]
                if d <= r - 0.2:
                    col = PAL["O"]
                if d <= r * 0.62:
                    col = PAL["Y"]
                if d <= 1.6:
                    col = PAL["W"]
                img.putpixel((x, y), col + (255,))
    return img


