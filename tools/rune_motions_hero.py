LEG_KEYS = ("body", "rl", "ll", "rk", "lk", "root", "head")
LUNGE_DEEP = dict(rl=[32, 0, 4], ll=[-48, 0, -2], rk=22, lk=54)  # 낮고 넓게 내디딘 다리 (왼발 앞)
