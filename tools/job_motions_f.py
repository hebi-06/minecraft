def up_right(m, wind_tick, hit_tick, end_tick, wind=None, hit=None, end=None):
    """올려 베기: wind_tick 에 오른쪽 아래 뒤로 감았다가 hit_tick 에 앞을 지나 end_tick 에 왼쪽 위로"""
