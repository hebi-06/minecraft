def ready_out(m, tick, fp=True):
    keyp(m, tick, P(W_READY, body=[6, 4, 0]))
    if fp:
        fpw(m, tick, FPW_LOW)


def catch(name, about, key, fp_hold):
    """던진 무기가 손으로 돌아옴: 손을 뻗어 받아 (0.6틱까지 빈손) 한 번 들썩이고 싸울 자세로"""
    m = Motion(name, 10, about, fade=(0.0, 0.12))
    m.set(hands={"main": "thrown"}, hide=[0.0, m.t(0.6)])
    keyp(m, 0.3, P(body=[4, -4, 0], ra=arm([0.25, 0.15, 0.96], 10, [0, 1, 0]), la=L(A_HIP), **LEGS_FIGHT))
    keyp(m, 1.6, P(body=[-2, 6, 0], ra=bent([0.35, -0.15, 0.55], 75, (0, 1, 0.3)), la=L(A_HIP), **LEGS_FIGHT), "out3")
    keyp(m, 4, P(body=[2, 0, 0], ra=RA_UPF, la=L(A_HIP), **LEGS_FIGHT), "out3")
    ready_out(m, 8, fp=False)
    fpr(m, 0.3, FP_PALM_UP)
    m.fp(0.7, (-0.2, 0.1, -0.15), None, None)
    fpw(m, 1.6, fp_hold, "out3")
    fpw(m, 4, FPW_UP, "out3")
    fpw(m, 8, FPW_LOW)
    use_skill(m, key)
    return m


